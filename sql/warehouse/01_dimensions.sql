-- ============================================================
-- Warehouse (Gold) layer - DIMENSIONS
-- Star schema from docs/erd/warehouse_erd.md
-- Surrogate keys on every dimension; natural keys kept as attributes.
-- Key -1 = "Unknown" member (used when a fact row cannot resolve a key).
-- Re-runnable: drops and recreates the warehouse tables.
-- ============================================================

CREATE SCHEMA IF NOT EXISTS warehouse;

-- Drop facts first (they reference the dimensions)
DROP TABLE IF EXISTS warehouse.fact_reviews  CASCADE;
DROP TABLE IF EXISTS warehouse.fact_payments CASCADE;
DROP TABLE IF EXISTS warehouse.fact_sales    CASCADE;
DROP TABLE IF EXISTS warehouse.dim_seller    CASCADE;
DROP TABLE IF EXISTS warehouse.dim_customer  CASCADE;
DROP TABLE IF EXISTS warehouse.dim_product   CASCADE;
DROP TABLE IF EXISTS warehouse.dim_geography CASCADE;
DROP TABLE IF EXISTS warehouse.dim_date      CASCADE;

-- ---------- dim_date (one calendar day, key = YYYYMMDD) ----------
CREATE TABLE warehouse.dim_date (
    date_key      integer  PRIMARY KEY,          -- 20180131
    full_date     date     NOT NULL UNIQUE,
    year          integer  NOT NULL,
    quarter       integer  NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    month         integer  NOT NULL CHECK (month BETWEEN 1 AND 12),
    month_name    varchar(20) NOT NULL,
    day           integer  NOT NULL CHECK (day BETWEEN 1 AND 31),
    day_of_week   integer  NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),  -- 1 = Monday (ISO)
    week_of_year  integer  NOT NULL CHECK (week_of_year BETWEEN 1 AND 53),
    is_weekend    boolean  NOT NULL
);

-- ---------- dim_geography (one zip-code prefix) ----------
CREATE TABLE warehouse.dim_geography (
    geography_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zip_code_prefix varchar(10) NOT NULL UNIQUE,
    city          varchar(100),
    state         char(2),
    latitude      numeric(10,6),
    longitude     numeric(10,6)
);

-- ---------- dim_customer (one REAL customer = customer_unique_id) ----------
CREATE TABLE warehouse.dim_customer (
    customer_key        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_unique_id  varchar(50) NOT NULL UNIQUE,
    geography_key       integer REFERENCES warehouse.dim_geography (geography_key),
    customer_zip_code_prefix varchar(10),
    customer_city       varchar(100),
    customer_state      char(2)
);
CREATE INDEX ON warehouse.dim_customer (geography_key);

-- ---------- dim_product ----------
CREATE TABLE warehouse.dim_product (
    product_key        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         varchar(50) NOT NULL UNIQUE,
    category_name_pt   varchar(100),
    category_name_en   varchar(100),
    name_length        integer,
    description_length integer,
    photos_qty         integer,
    weight_g           numeric,
    length_cm          numeric,
    height_cm          numeric,
    width_cm           numeric
);

-- ---------- dim_seller ----------
CREATE TABLE warehouse.dim_seller (
    seller_key          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id           varchar(50) NOT NULL UNIQUE,
    geography_key       integer REFERENCES warehouse.dim_geography (geography_key),
    seller_zip_code_prefix varchar(10),
    seller_city         varchar(100),
    seller_state        char(2)
);
CREATE INDEX ON warehouse.dim_seller (geography_key);

-- ---------- Unknown members (key = -1) ----------
